async function run() {
  const dataSource = new DataSource({
    type: 'postgres',
    host: process.env.DB_HOST,
    port: Number(process.env.DB_PORT ?? 5432),
    username: process.env.DB_USERNAME,
    password: process.env.DB_PASSWORD,
    database: process.env.DB_NAME,
    ssl: process.env.DB_SSL === 'true' ? { rejectUnauthorized: false } : false,
    // se registran todas las entities (no solo Ingredient) porque TypeORM necesita
    // resolver las relaciones inversas declaradas en Ingredient (inventoryItems, prices, etc.)
    entities: [path.join(__dirname, '../../modules/**/*.entity.{ts,js}')],
  });

  await dataSource.initialize();
  const repository = dataSource.getRepository(Ingredient);

  let created = 0;
  let skipped = 0;
  for (const data of seedIngredients) {
    const existing = await repository.findOne({ where: { name: data.name } });
    if (existing) {
      skipped++;
      continue;
    }
    await repository.save(repository.create(data));
    created++;
  }

  console.log(
    `Seed de ingredientes: ${created} creados, ${skipped} ya existían.`,
  );
  await dataSource.destroy();
}

run().catch((error) => {
  console.error('Error corriendo el seed:', error);
  process.exit(1);
});
